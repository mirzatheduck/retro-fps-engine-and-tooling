"""Export computed mesh metadata and geometry to C99, JSON, Unreal and Unity."""
import csv
import json
from pathlib import Path
import re

GENERATED_BY = 'tooling_python/mesh_and_config_pipeline.py'
FIELDS = ('name', 'source_path', 'lowpoly_path', 'tris_before', 'tris_after',
          'verts_before', 'verts_after', 'non_manifold_edges', 'degenerate_faces_removed',
          'duplicate_vertices_merged', 'bytes_before', 'bytes_after', 'memory_saved_pct',
          'snap_grid', 'compat_score', 'bounds_min', 'bounds_max', 'stages')
INTEGER_FIELDS = ('tris_before', 'tris_after', 'verts_before', 'verts_after',
                  'non_manifold_edges', 'degenerate_faces_removed', 'duplicate_vertices_merged',
                  'bytes_before', 'bytes_after')


def _write(path, text):
    path = Path(path)
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(text, encoding='utf-8', newline='\n')


def _float(value):
    return f'{value:.6f}f'


def _symbol(name):
    return 'ASSET_' + re.sub('[^A-Za-z0-9_]', '_', name).upper()


def _array(lines, declaration, values):
    lines.append(declaration + ' = {')
    for offset in range(0, len(values), 8):
        lines.append('    ' + ', '.join(values[offset:offset + 8]) + ',')
    lines.append('};')


def export_c99_header(assets, path):
    """Emit the fixed unsigned-short ABI; reject geometry it cannot represent."""
    if not assets:
        raise ValueError('C manifest requires at least one asset')
    lines = [f'/* AUTO-GENERATED by {GENERATED_BY} - DO NOT EDIT BY HAND */',
             '#ifndef ASSET_MANIFEST_H', '#define ASSET_MANIFEST_H', '',
             '#define ASSET_MANIFEST_VERSION 1', f'#define ASSET_MANIFEST_COUNT {len(assets)}', '']
    for asset in assets:
        vertices, faces = asset['vertices'], asset['faces']
        if not vertices or not faces or len(vertices) > 65536:
            raise ValueError('C99 contract needs nonempty geometry with at most 65536 vertices')
        symbol = _symbol(asset['name'])
        lines.extend((f'#define {symbol}_VERTEX_COUNT {len(vertices)}',
                      f'#define {symbol}_INDEX_COUNT {len(faces) * 3}'))
        _array(lines, f'static const float {symbol}_VERTICES[{symbol}_VERTEX_COUNT * 3]',
               [_float(value) for vertex in vertices for value in vertex])
        _array(lines, f'static const unsigned short {symbol}_INDICES[{symbol}_INDEX_COUNT]',
               [str(index) for face in faces for index in face])
        lines.append('')
    lines.extend(('typedef struct AssetManifestEntry {',
                  '    const char *name;', '    const char *source_path;', '    const char *lowpoly_path;'))
    lines.extend('    int ' + field + ';' for field in INTEGER_FIELDS[:7])
    lines.extend(('    unsigned int bytes_before;', '    unsigned int bytes_after;',
                  '    float snap_grid;', '    float compat_score;',
                  '    float bounds_min[3];', '    float bounds_max[3];',
                  '    const float *vertices;', '    const unsigned short *indices;',
                  '    int vertex_count;', '    int index_count;', '} AssetManifestEntry;', '',
                  'static const AssetManifestEntry ASSET_MANIFEST[ASSET_MANIFEST_COUNT] = {'))
    for asset in assets:
        symbol = _symbol(asset['name'])
        strings = ', '.join(json.dumps(asset[key], ensure_ascii=True) for key in ('name', 'source_path', 'lowpoly_path'))
        numbers = ', '.join(str(asset[key]) for key in INTEGER_FIELDS)
        lines.extend(('    { ' + strings + ',', '      ' + numbers + ',',
                      f'      {_float(asset["snap_grid"])}, {_float(asset["compat_score"])},',
                      '      { ' + ', '.join(_float(v) for v in asset['bounds_min']) + ' },',
                      '      { ' + ', '.join(_float(v) for v in asset['bounds_max']) + ' },',
                      f'      {symbol}_VERTICES, {symbol}_INDICES,',
                      f'      {symbol}_VERTEX_COUNT, {symbol}_INDEX_COUNT }},'))
    lines.extend(('};', '', '#endif /* ASSET_MANIFEST_H */', ''))
    _write(path, '\n'.join(lines))


def export_json(assets, path):
    budgets = {asset['budget'] for asset in assets}
    if len(budgets) != 1:
        raise ValueError('JSON manifest requires a shared budget')
    data = {'version': 1, 'generated_by': GENERATED_BY, 'budget': budgets.pop(),
            'assets': [{key: asset[key] for key in FIELDS} for asset in assets]}
    _write(path, json.dumps(data, indent=2, ensure_ascii=False, allow_nan=False) + '\n')


def export_unreal_datatable(assets, path):
    """CSV fields map to a matching Unreal row struct; vectors use FVector syntax.

    Stages is a JSON string field so no nested UE struct is required for logs.
    The first column is Unreal's required row-name column.
    """
    path = Path(path)
    path.parent.mkdir(parents=True, exist_ok=True)
    with path.open('w', encoding='utf-8', newline='') as stream:
        writer = csv.writer(stream)
        writer.writerow(['---', *FIELDS])
        for asset in assets:
            values = []
            for key in FIELDS:
                value = asset[key]
                if key in ('bounds_min', 'bounds_max'):
                    value = '(' + ','.join(f'{axis}={number:.12g}' for axis, number in zip('XYZ', value)) + ')'
                elif key == 'stages':
                    value = json.dumps(value, ensure_ascii=False)
                values.append(value)
            writer.writerow([asset['name'], *values])


def export_unity_scriptable(assets, path):
    """Self-contained serializable structs and static manifest, no Unity API needed."""
    lines = ['// AUTO-GENERATED - DO NOT EDIT BY HAND', 'using System;', '',
             '[Serializable]', 'public struct RetroAssetStage {',
             '    public string stage;', '    public string message;', '}', '',
             '[Serializable]', 'public struct RetroAssetEntry {']
    for key in FIELDS:
        kind = ('string' if key in ('name', 'source_path', 'lowpoly_path') else
                'int' if key in INTEGER_FIELDS[:7] else 'uint' if key in INTEGER_FIELDS[7:] else
                'float[]' if key in ('bounds_min', 'bounds_max') else
                'RetroAssetStage[]' if key == 'stages' else 'float')
        lines.append(f'    public {kind} {key};')
    lines.extend(('}', '', 'public static class RetroAssetManifest {',
                  '    public const int Version = 1;',
                  '    public static readonly RetroAssetEntry[] Assets = new RetroAssetEntry[] {'))
    for asset in assets:
        lines.append('        new RetroAssetEntry {')
        for key in FIELDS:
            value = asset[key]
            if isinstance(value, str):
                literal = json.dumps(value, ensure_ascii=True)
            elif key == 'stages':
                literal = 'new RetroAssetStage[] { ' + ', '.join(
                    'new RetroAssetStage { stage = ' + json.dumps(stage['stage']) +
                    ', message = ' + json.dumps(stage['message']) + ' }' for stage in value) + ' }'
            elif isinstance(value, list):
                literal = 'new float[] { ' + ', '.join(_float(v) for v in value) + ' }'
            elif key in INTEGER_FIELDS:
                literal = str(value) + ('u' if key in INTEGER_FIELDS[7:] else '')
            else:
                literal = _float(value)
            lines.append(f'            {key} = {literal},')
        lines.append('        },')
    lines.extend(('    };', '}', ''))
    _write(path, '\n'.join(lines))


def export_obj(mesh, path):
    lines = ['# AUTO-GENERATED vertex-clustered retro mesh']
    lines.extend('v ' + ' '.join(f'{value:.12f}' for value in vertex) for vertex in mesh.vertices)
    lines.extend('f ' + ' '.join(str(index + 1) for index in face) for face in mesh.faces)
    _write(path, '\n'.join(lines) + '\n')
